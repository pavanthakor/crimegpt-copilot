const TABLE: Record<Lang, Dict> = { EN: en, HI: hi, GU: gu };

export type TKey = keyof typeof en;

function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, k) =>
    k in vars ? String(vars[k]) : `{${k}}`
  );
}

type Ctx = {
  lang: Lang;
  setLang: (l: Lang) => void;
  apiLang: string; // en | hi | gu — for ?lang= and the transcribe form
  t: (key: TKey, vars?: Record<string, string | number>) => string;
};

const LanguageContext = createContext<Ctx | undefined>(undefined);

function readStored(): Lang {
  if (typeof window === "undefined") return "EN";
  const v = window.localStorage.getItem(STORAGE_KEY);
  return v === "HI" || v === "GU" || v === "EN" ? v : "EN";
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("EN");

  // Read the persisted choice on the client (avoids an SSR/CSR mismatch).
  useEffect(() => {
    const stored = readStored();
    setLangState(stored);
    document.documentElement.lang = API_LANG[stored];
  }, []);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    window.localStorage.setItem(STORAGE_KEY, l);
    document.documentElement.lang = API_LANG[l];
  }, []);

  const t = useCallback(
    (key: TKey, vars?: Record<string, string | number>) => {
      const table = TABLE[lang];
      // Fall back to English if a key is somehow missing in a table, then to the
      // key itself — never render blank.
      const raw = table[key] ?? en[key] ?? String(key);
      return interpolate(raw, vars);
    },
    [lang]
  );

  return createElement(
    LanguageContext.Provider,
    { value: { lang, setLang, apiLang: API_LANG[lang], t } },
    children
  );
}

export function useI18n(): Ctx {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error("useI18n must be used within LanguageProvider");
  return ctx;
}
